def maior_numero(a, b):
    """Função que recebe dois números e retorna o maior entre eles."""
    if a > b:
        print(f"O maior número é: {a}")
    else:
        print(f"O maior número é: {b}")

# Exemplo de uso da função
if __name__ == "__main__":
    maior_numero(10, 5)

